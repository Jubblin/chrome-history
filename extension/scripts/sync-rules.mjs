// Single source of truth: internal/classify/rules.json.
// `node scripts/sync-rules.mjs`          copies it into src/classify/
// `node scripts/sync-rules.mjs --check`  exits 1 if the copies differ
import { readFileSync, writeFileSync } from 'node:fs';

const src = new URL('../../internal/classify/rules.json', import.meta.url);
const outJson = new URL('../src/classify/rules.json', import.meta.url);
const outJs = new URL('../src/classify/rules.js', import.meta.url);

const text = readFileSync(src, 'utf8');
JSON.parse(text);
const js = `// GENERATED by scripts/sync-rules.mjs from internal/classify/rules.json. Do not edit.\nexport default ${text.trimEnd()};\n`;

if (process.argv.includes('--check')) {
  const read = (u) => { try { return readFileSync(u, 'utf8'); } catch { return null; } };
  const bad = [];
  if (read(outJson) !== text) bad.push('src/classify/rules.json');
  if (read(outJs) !== js) bad.push('src/classify/rules.js');
  if (bad.length) {
    console.error(`out of date: ${bad.join(', ')} (run: make extension-sync)`);
    process.exit(1);
  }
  console.log('rules in sync');
} else {
  writeFileSync(outJson, text);
  writeFileSync(outJs, js);
  console.log('rules synced');
}
