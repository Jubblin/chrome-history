// Single source of truth: shared/ui-common.js.
// `node scripts/sync-ui-common.mjs`          copies it into ui/ (extension) and ../web/static/
// `node scripts/sync-ui-common.mjs --check`  exits 1 if the copies differ
import { readFileSync, writeFileSync } from 'node:fs';

const src = new URL('../../shared/ui-common.js', import.meta.url);
const outs = [
  ['extension/ui/ui-common.js', new URL('../ui/ui-common.js', import.meta.url)],
  ['web/static/ui-common.js', new URL('../../web/static/ui-common.js', import.meta.url)],
];

const lf = (s) => s.replace(/\r\n/g, '\n');
const text = lf(readFileSync(src, 'utf8'));
const out = `// GENERATED by scripts/sync-ui-common.mjs from shared/ui-common.js. Do not edit.\n${text}`;

if (process.argv.includes('--check')) {
  const bad = outs.filter(([, u]) => { try { return lf(readFileSync(u, 'utf8')) !== out; } catch { return true; } }).map(([n]) => n);
  if (bad.length) {
    console.error(`out of date: ${bad.join(', ')} (run: make ui-sync)`);
    process.exit(1);
  }
  console.log('ui-common in sync');
} else {
  for (const [, u] of outs) writeFileSync(u, out);
  console.log('ui-common synced');
}
